def visualize_simulation(sdf_grid=None, particles=None, domain_size=2.0, title="Simulation Result"):
    """
    [통합 뷰어] 왼쪽에는 2D 단면, 오른쪽에는 3D 메쉬+파티클을 보여줍니다.
    """
    fig = plt.figure(figsize=(14, 6))
    
    # --- 왼쪽: 2D Slice ---
    ax1 = fig.add_subplot(1, 2, 1)
    if sdf_grid is not None:
        im = draw_2d_slice(ax1, sdf_grid, particles, axis=2, domain_size=domain_size)
        plt.colorbar(im, ax=ax1, label='SDF Value')
    else:
        ax1.text(0.5, 0.5, "No SDF Data", ha='center')

    # --- 오른쪽: 3D Mesh + Particles ---
    ax2 = fig.add_subplot(1, 2, 2, projection='3d')
    if sdf_grid is not None:
        draw_sdf_mesh(ax2, sdf_grid, domain_size)
    if particles is not None:
        draw_particles(ax2, particles)
        
    # 3D 축 설정
    limit = domain_size / 2.0
    ax2.set_xlim(-limit, limit); ax2.set_ylim(-limit, limit); ax2.set_zlim(-limit, limit)
    ax2.set_title(f"{title} (3D View)")
    
    plt.tight_layout()
    plt.show()


def visualize_npy(filepath, domain_size=2.0):
    """
    .npy 파일을 로드하여 시각화합니다.
    """
    try:
        data = np.load(filepath)
        print(f"📂 '{filepath}' 로드 성공! Shape: {data.shape}")
        
        # 데이터 모양에 따라 처리 (그리드인지 파티클인지)
        if len(data.shape) == 3: # SDF 그리드 (N,N,N)
            visualize_simulation(sdf_grid=data, domain_size=domain_size, title="Loaded SDF Grid")
        elif len(data.shape) == 2 and data.shape[1] == 3: # 파티클 (M,3)
            visualize_simulation(particles=data, domain_size=domain_size, title="Loaded Particles")
        else:
            print("❌ 알 수 없는 데이터 형식입니다.")
            
    except FileNotFoundError:
        print(f"❌ 파일을 찾을 수 없습니다: {filepath}")


def view_obj_interactive(filename="output.obj"):
    """
    Open3D를 사용하여 OBJ 파일을 별도의 창에서 인터랙티브하게 봅니다.
    마우스로 회전(좌클릭), 이동(우클릭), 줌(휠)이 가능합니다.
    """
    if not os.path.exists(filename):
        print(f"❌ 파일을 찾을 수 없습니다: {filename}")
        return

    print(f"🖥️ 3D 뷰어 실행 중: {filename} ...")
    
    try:
        # 1. 메쉬 읽기
        mesh = o3d.io.read_triangle_mesh(filename)
        
        # 2. 렌더링 품질 향상을 위한 법선 벡터(Normal) 계산
        # (이게 없으면 모델이 평평해 보임)
        mesh.compute_vertex_normals()
        
        # 3. 좌표축 표시 (선택사항)
        coord_frame = o3d.geometry.TriangleMesh.create_coordinate_frame(size=0.5, origin=[0, 0, 0])
        
        # 4. 시각화 창 띄우기
        o3d.visualization.draw_geometries(
            [mesh, coord_frame], 
            window_name="SDF 3D Viewer",
            width=800,
            height=600,
            left=50,
            top=50
        )
        print("✅ 뷰어 종료됨.")
        
    except Exception as e:
        print(f"❌ 뷰어 실행 중 오류 발생: {e}")

        
def view_obj_and_particles_interactive(filename="output.obj", particles=None, resolution=128, domain_size=2.0):
    """
    OBJ 메쉬를 월드 좌표로 실시간 변환하여 파티클과 함께 시각화합니다.
    
    Args:
        filename: OBJ 파일 경로 (0 ~ resolution-1 좌표계)
        particles: 파티클 데이터 (N, 3) - (-1 ~ 1 좌표계 권장)
        resolution: SDF 그리드 해상도 (기본값 128)
        domain_size: 실제 월드 도메인 크기 (기본값 2.0)
    """
    if not os.path.exists(filename):
        print(f"❌ 파일을 찾을 수 없습니다: {filename}")
        return

    print(f"🖥️ 3D 뷰어 실행 중 (실시간 좌표 변환 적용): {filename} ...")
    
    try:
        geometries = []

        # 1. 메쉬 로드
        mesh = o3d.io.read_triangle_mesh(filename)
        
        # 🚨 [핵심] 메쉬 정점 좌표 변환 (Index Space -> World Space)
        # verts_world = (verts / (resolution - 1)) * domain_size - (domain_size / 2.0)
        verts = np.asarray(mesh.vertices)
        
        # 유저님이 요청하신 공식 적용
        verts_world = (verts / (resolution - 1)) * domain_size - (domain_size / 2.0)
        
        # 변환된 좌표를 다시 메쉬에 주입
        mesh.vertices = o3d.utility.Vector3dVector(verts_world)
        
        # 좌표가 바뀌었으므로 법선 벡터(Normals)를 다시 계산해야 쉐이딩이 깨지지 않습니다.
        mesh.compute_vertex_normals()
        mesh.paint_uniform_color([0.7, 0.7, 0.7]) 
        geometries.append(mesh)

        # 2. 파티클 세팅
        if particles is not None:
            if hasattr(particles, 'cpu'):
                particles_np = particles.cpu().numpy()
            else:
                particles_np = np.array(particles)
                
            pcd = o3d.geometry.PointCloud()
            pcd.points = o3d.utility.Vector3dVector(particles_np)
            
            # 파티클 색상 (밝은 파란색)
            colors = np.zeros_like(particles_np)
            colors[:, 0], colors[:, 1], colors[:, 2] = 0.1, 0.5, 1.0
            pcd.colors = o3d.utility.Vector3dVector(colors)
            
            geometries.append(pcd)
            print(f"✅ 파티클 {len(particles_np):,}개 정렬 완료.")

        # 3. 좌표축 및 렌더링
        coord_frame = o3d.geometry.TriangleMesh.create_coordinate_frame(size=0.3, origin=[0, 0, 0])
        geometries.append(coord_frame)
        
        print(f"🔍 메쉬 범위 확인: {verts_world.min():.2f} ~ {verts_world.max():.2f}")
        
        o3d.visualization.draw_geometries(
            geometries, 
            window_name="On-the-fly Scaled SDF Viewer",
            width=1024, height=768
        )
        
    except Exception as e:
        print(f"❌ 시각화 실패: {e}")


