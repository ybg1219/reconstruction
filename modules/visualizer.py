# 1. 3D 시각화 관련 함수들 (이전과 동일)
# =========================================================

def draw_sdf_mesh(ax, sdf_grid, domain_size=2.0, level=0, color='skyblue', alpha=0.2):
    """3D 축에 SDF 메쉬를 그림"""
    try:
        verts, faces, normals, values = measure.marching_cubes(sdf_grid, level=level)
        resolution = sdf_grid.shape[0]
        min_bound = -domain_size / 2.0
        voxel_size = domain_size / (resolution - 1)
        verts_world = min_bound + verts * voxel_size
        
        mesh = Poly3DCollection(verts_world[faces], alpha=alpha)
        mesh.set_facecolor(color)
        mesh.set_edgecolor('gray')
        mesh.set_linewidth(0.05)
        ax.add_collection3d(mesh)
        return True
    except (ValueError, RuntimeError):
        return False

def draw_particles(ax, particles, color='orange', size=3, max_show=2000):
    """3D 축에 파티클을 그림"""
    if particles is None or len(particles) == 0: return
    
    p_show = particles[::(len(particles)//max_show)] if len(particles) > max_show else particles
    ax.scatter(p_show[:, 0], p_show[:, 1], p_show[:, 2], 
               s=size, c=color, alpha=0.8, label=f'Particles ({len(particles)})')

# =========================================================
# 2. 2D 단면 시각화 관련 함수들 (리팩토링 핵심)
# =========================================================

def draw_2d_slice(ax, sdf_grid, particles=None, axis=2, slice_idx=None, domain_size=2.0):
    """
    SDF 그리드의 단면을 자르고, 필요시 파티클을 투영하여 그립니다.
    """
    N = sdf_grid.shape[axis]
    if slice_idx is None:
        slice_idx = N // 2 # 중앙

    # 1. 단면 자르기 (Slicing)
    if axis == 0:   # X축 기준 자르기 (YZ 평면)
        data_slice = sdf_grid[slice_idx, :, :]
        idx_x_particle, idx_y_particle = 1, 2 # 파티클의 Y, Z 좌표 사용
        xlabel, ylabel = 'Y', 'Z'
    elif axis == 1: # Y축 기준 자르기 (XZ 평면)
        data_slice = sdf_grid[:, slice_idx, :]
        idx_x_particle, idx_y_particle = 0, 2 # 파티클의 X, Z 좌표 사용
        xlabel, ylabel = 'X', 'Z'
    else:           # Z축 기준 자르기 (XY 평면)
        data_slice = sdf_grid[:, :, slice_idx]
        idx_x_particle, idx_y_particle = 0, 1 # 파티클의 X, Y 좌표 사용
        xlabel, ylabel = 'X', 'Y'

    # 2. 히트맵 그리기
    im = ax.imshow(data_slice.T, # 축 방향에 따라 전치 필요할 수 있음 (여기선 보정)
                   cmap='RdBu', vmin=-1, vmax=1, origin='lower')
    ax.contour(data_slice.T, 
               levels=[0], colors='black', linewidths=2)
    
    # 3. 파티클 오버레이 (World -> Grid Index 변환 및 투영)
    if particles is not None and len(particles) > 0:
        resolution = sdf_grid.shape[0]
        voxel_size = domain_size / (resolution - 1)
        min_bound = -domain_size / 2.0

        # 파티클 좌표를 그리드 인덱스로 변환
        p_indices = (particles - min_bound) / voxel_size
        
        # 현재 슬라이스 두께(1칸) 안에 들어오는 파티클만 필터링
        # 예: Z축 슬라이스면, 파티클의 Z 인덱스가 slice_idx와 비슷한 것만 골라냄
        slice_axis_idx = axis
        mask = np.abs(p_indices[:, slice_axis_idx] - slice_idx) < 0.6 # ±0.6칸 이내
        
        valid_p = p_indices[mask]
        
        # 필터링된 파티클 그리기
        ax.scatter(valid_p[:, idx_x_particle], valid_p[:, idx_y_particle], 
                   s=10, c='yellow', edgecolors='k', alpha=0.8, label='Particles')
        ax.legend(loc='upper right', fontsize='small')

    ax.set_title(f"2D Slice ({ylabel} vs {xlabel}) @ idx={slice_idx}")
    ax.set_xlabel(f"{xlabel} Index")
    ax.set_ylabel(f"{ylabel} Index")
    return im

